"""Generate a rational disk cover for a freely moving eighteenth square."""
import argparse
from fractions import Fraction as Q
from pathlib import Path

from free_tile import check_fixed

SIDE = Q(97, 20)
EPS = Q(1, 32)
HALF = Q(1, 2)
CAP = Q(17, 40)


def near_coordinate(value):
    return max(-CAP, min(CAP, Q(round(value*256), 256)))


def literal(q):
    return f"({q.numerator}/{q.denominator} : ℚ)" if q.denominator != 1 else f"({q.numerator} : ℚ)"


def make_tree(rect, tiles, stats, leaves):
    xl, xh, yl, yh = rect
    x, y = (xl+xh)/2, (yl+yh)/2
    for i, (ox, oy, (c,s)) in enumerate(tiles):
        # Proxy for the closest point to the cell centre, with a margin to
        # the walls of the fixed square. Only the exact tests below matter.
        a = near_coordinate((x-ox)*c + (y-oy)*s)
        b = near_coordinate(-(x-ox)*s + (y-oy)*c)
        px, py = ox+a*c-b*s, oy+a*s+b*c
        margin = EPS * (abs(px-ox) + abs(py-oy) + Q(3,2))
        if max(abs(a),abs(b)) + margin >= HALF:
            continue
        if (max(abs(px-xl),abs(px-xh))**2 +
            max(abs(py-yl),abs(py-yh))**2 >= HALF**2):
            continue
        stats["leaves"] += 1
        leaves.append((rect, i))
        return f"(.leaf {i} {literal(a)} {literal(b)})"
    if max(xh-xl,yh-yl) < Q(1, 2**18):
        raise ValueError(f"No interior disk witness found for cell {rect}")
    if xh-xl >= yh-yl:
        left, right = (xl,x,yl,yh), (x,xh,yl,yh)
        split = "vertical"
    else:
        left, right = (xl,xh,yl,y), (xl,xh,y,yh)
        split = "horizontal"
    return f"(.{split}\n{make_tree(left, tiles, stats, leaves)}\n{make_tree(right, tiles, stats, leaves)})"


def draw(path, tiles, leaves):
    """Show the reference tiles and the proven partition in the same coordinates."""
    from xml.etree.ElementTree import Element, SubElement, tostring
    img = Element("svg", xmlns="http://www.w3.org/2000/svg", viewBox="0 0 754 419", role="img")
    SubElement(img, "title").text = "Seventeen reference squares and the exclusion of an eighteenth"
    SubElement(img, "desc").text = ("Left: the 17 reference squares. Right: 188 cells for the centre "
        "of the additional square. Each cell matches the colour of a tile forced to intersect it.")
    def text(x, y, message, **attrs):
        SubElement(img,"text",{"x":str(x),"y":str(y),"font-family":"sans-serif",**attrs}).text=message
    def val(q):
        return f"{float(q):.3f}"
    def colour(i):
        return f"hsl({(i*137)%360},47%,72%)"
    for offset, label in ((19,"Reference layout"),(393,"Possible centres of the free square")):
        text(offset,24,label,**{"font-size":"17","font-weight":"600"})
        SubElement(img,"rect",x=str(offset),y="40",width="340",height="340",fill="#fbfcfd",stroke="#243445")
    scale=340/SIDE
    for i,(x,y,(c,s)) in enumerate(tiles):
        pts=[(19+scale*(x+(a*c-b*s)/2),380-scale*(y+(a*s+b*c)/2))
             for a,b in ((1,1),(-1,1),(-1,-1),(1,-1))]
        SubElement(img,"polygon",points=" ".join(f"{val(X)},{val(Y)}" for X,Y in pts),
                   fill=colour(i),stroke="#293847")
        text(val(19+scale*x),val(384-scale*y),str(i+1),**{"font-size":"11","text-anchor":"middle"})
    for (xl,xh,yl,yh),i in leaves:
        SubElement(img,"rect",x=val(393+scale*xl),y=val(380-scale*yh),width=val(scale*(xh-xl)),
                   height=val(scale*(yh-yl)),fill=colour(i),stroke="#53606c",**{"stroke-width":".4"})
    text(19,405,"Container side 4.85",**{"font-size":"13"})
    text(393,405,"Cell colour identifies a tile that forces an overlap.",**{"font-size":"13"})
    path.write_bytes(tostring(img,encoding="utf-8")+b"\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    base = Path(__file__).resolve().parent
    parser.add_argument("--output",type=Path,default=base/"CoverData.lean")
    parser.add_argument("--witness",type=Path,default=base.parent/"finite/witness-17.txt")
    parser.add_argument("--figure",type=Path,help="also draw the reference layout and certified leaves")
    args = parser.parse_args()
    tiles = check_fixed(args.witness,SIDE)
    stats = {"leaves":0}
    leaves = []
    tree = make_tree((HALF,SIDE-HALF,HALF,SIDE-HALF),tiles,stats,leaves)
    if args.figure:
        draw(args.figure,tiles,leaves)
    entries = ["  ⟨"+", ".join(literal(v) for v in (x,y,c,s))+"⟩" for x,y,(c,s) in tiles]
    header="""import ConjectureLab.InsertionCover

/-! Generated by make_cover.py from the 17 exact poses in finite/witness-17.txt. -/
namespace Pack18Cover
open ConjectureLab.SquarePacking ConjectureLab.InsertionCover

"""
    text = header + "def frames : Array Placement := #[\n"+",\n".join(entries)+"\n]\n\n"
    text += "def reference (i : Fin 17) : Placement := frames[i.val]'(by simp [frames])\n\n"
    text += """theorem reference_fits : IsPacking ((12057189 / 2500000 : ℚ) : ℝ) reference :=
  ConjectureLab.SquarePacking.check_sound (L := (12057189 / 2500000 : ℚ)) (by decide +kernel)

"""
    text += "def tree : Tree :=\n"+tree+"\n\n"
    text += "set_option maxRecDepth 32768 in\ntheorem accepted : check reference tree = true := by decide +kernel\n\n"
    text += """theorem noInsertion (moving : Fin 17 → Pose)
    (framesUnit : ∀ i, UnitFrame (moving i)) (near : ∀ i, Close (reference i) (moving i))
    (free : Pose) (unitFree : UnitFrame free) {L : ℝ} (size : L ≤ 97/20)
    (inside : Contained L free) : ∃ i z, z ∈ OpenTile (moving i) ∧ z ∈ OpenTile free :=
  collision_of_contained accepted moving framesUnit near free unitFree size inside

#print axioms noInsertion
end Pack18Cover
"""
    args.output.write_text(text)
    print(f"Generated {stats['leaves']} disk witnesses and {stats['leaves']-1} bisections.")


if __name__ == "__main__":
    main()
